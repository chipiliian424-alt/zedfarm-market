let currentLang = localStorage.getItem('zedfarm_lang') || 'en';
if (!LANGS[currentLang]) currentLang = 'en';

export function getLang() { return currentLang; }

export function t(key) {
  const table = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  if (table[key] != null) return table[key];
  if (TRANSLATIONS.en[key] != null) return TRANSLATIONS.en[key];
  return key;
}

export function setLang(lang) {
  if (!LANGS[lang]) return;
  currentLang = lang;
  localStorage.setItem('zedfarm_lang', lang);
  document.documentElement.lang = LANGS[lang].htmlLang;
  applyTranslations(document);
  document.dispatchEvent(new CustomEvent('zedfarm:langchange', { detail: { lang } }));
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.title = t('site.title');
}

export function initI18n() {
  document.documentElement.lang = LANGS[currentLang].htmlLang;
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyTranslations(document));
  } else {
    applyTranslations(document);
  }
}

export { LANGS, TRANSLATIONS };
